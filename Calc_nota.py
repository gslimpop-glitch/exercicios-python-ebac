#coloca if variavel elif variavel elif variavel se não da erro, nao esquece o nome da variavel na função

nota = float(input())

if nota >= 7.0:
    print("Aprovado")
elif  nota >= 5.0 and nota < 7.0:
      print("Recuperação")
else:
      print("Reprovado")        

